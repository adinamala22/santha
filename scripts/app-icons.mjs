#!/usr/bin/env node
// Generates the launcher icons of the three Flutter apps from the brand app icons in design/brand/app-icon/.
//   node scripts/app-icons.mjs
//
//   Santha          (apps/consumer)  santha-app-icon.svg           indigo (brand default)
//   Santha Partner  (apps/merchant)  santha-app-icon-marigold.svg  marigold
//   Santha Rider    (apps/rider)     santha-app-icon-light.svg     light
//
// Android: legacy mipmap ic_launcher.png, and an adaptive icon. Per the design system, the adaptive
// foreground is the mark on transparent, inside the 66 dp safe zone, over the variant's background colour.
// iOS: every file in AppIcon.appiconset, square and opaque (iOS applies its own mask).
// The artwork is only scaled, never recoloured (logo rules in .claude/skills/santha-design-system).
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// sharp comes with Next.js (image optimisation) in the web app; resolve it through next.
const fromWeb = createRequire(join(root, 'apps/web/package.json'));
const sharp = createRequire(fromWeb.resolve('next/package.json'))('sharp');

const APPS = [
  { app: 'consumer', icon: 'santha-app-icon.svg' },
  { app: 'merchant', icon: 'santha-app-icon-marigold.svg' },
  { app: 'rider', icon: 'santha-app-icon-light.svg' },
];
const DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };

// The pin in the 512 × 512 artwork spans y 63–402 (centre 232.6) around x = 256.
const PIN = { cx: 256, cy: 232.6, height: 339.2 };

function parts(svg) {
  const body = svg.replace(/<metadata>[\s\S]*?<\/metadata>/, '');
  const bg = body.match(/<rect width="512" height="512" rx="[\d.]+" fill="(#[0-9A-Fa-f]{6})"\/>/);
  if (!bg) throw new Error('unexpected app icon SVG: no background rect');
  const inner = body.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  return { background: bg[1], inner, mark: inner.replace(bg[0], '') };
}

const png = (svg, size, opts = {}) => {
  let img = sharp(Buffer.from(svg), { density: 72 * (size / 512) * 4 }).resize(size, size);
  if (opts.flatten) img = img.flatten({ background: opts.flatten });
  return img.png().toBuffer();
};

for (const { app, icon } of APPS) {
  const { background, inner, mark } = parts(readFileSync(join(root, 'design/brand/app-icon', icon), 'utf8'));
  const res = join(root, 'apps', app, 'android/app/src/main/res');

  // Legacy launchers: the brand icon as drawn (rounded square).
  const full = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">${inner}</svg>`;
  // Adaptive foreground: the pin is 48 dp tall, centred in 108 dp. Launchers show about 72 dp of it, so this keeps
  // the brand clear space around the mark (checked on a Pixel launcher).
  const s = 48 / PIN.height;
  const fg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108"><g transform="translate(54 54) scale(${s}) translate(${-PIN.cx} ${-PIN.cy})">${mark}</g></svg>`;
  for (const [d, k] of Object.entries(DENSITIES)) {
    mkdirSync(join(res, `mipmap-${d}`), { recursive: true });
    writeFileSync(join(res, `mipmap-${d}`, 'ic_launcher.png'), await png(full, Math.round(48 * k)));
    writeFileSync(join(res, `mipmap-${d}`, 'ic_launcher_foreground.png'), await png(fg, Math.round(108 * k)));
  }
  mkdirSync(join(res, 'mipmap-anydpi-v26'), { recursive: true });
  writeFileSync(
    join(res, 'mipmap-anydpi-v26/ic_launcher.xml'),
    `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/app-icons.mjs from design/brand/app-icon/${icon}. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>
`,
  );
  writeFileSync(
    join(res, 'values/ic_launcher_background.xml'),
    `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/app-icons.mjs: background of ${icon}. -->
<resources>
    <color name="ic_launcher_background">${background}</color>
</resources>
`,
  );

  // iOS: square, opaque, at every size the asset catalogue lists.
  const square = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">${inner.replace(/(<rect width="512" height="512") rx="[\d.]+"/, '$1')}</svg>`;
  const set = join(root, 'apps', app, 'ios/Runner/Assets.xcassets/AppIcon.appiconset');
  const files = readdirSync(set).filter((f) => f.endsWith('.png'));
  for (const f of files) {
    const { width } = await sharp(join(set, f)).metadata();
    writeFileSync(join(set, f), await png(square, width, { flatten: background }));
  }
  console.log(`${app}: ${icon} → Android (5 densities + adaptive, background ${background}), iOS (${files.length} sizes)`);
}
