import { createZodDto } from 'nestjs-zod';
import { z } from 'zod';

const deviceId = z
  .string()
  .min(8)
  .max(128)
  .regex(/^[A-Za-z0-9._:-]+$/)
  .describe('Stable per-install id generated by the app and kept in secure storage');
const signupApp = z.enum(['consumer', 'merchant', 'rider']).describe('Which Santha app is signing in');
const role = z.enum(['consumer', 'merchant', 'merchant_staff', 'rider', 'admin', 'ops', 'finance', 'support']);

export const OtpRequestSchema = z
  .object({
    phone: z.string().min(10).max(16).describe('Indian mobile; normalised to +91XXXXXXXXXX'),
    deviceId,
    app: signupApp,
    locale: z.enum(['en', 'te']).optional().describe('Language for the SMS'),
  });
export class OtpRequestDto extends createZodDto(OtpRequestSchema) {}

export const OtpChallengeSchema = z
  .object({
    challengeId: z.uuid(),
    expiresInSec: z.number().int(),
    resendAfterSec: z.number().int(),
  });
export class OtpChallengeDto extends createZodDto(OtpChallengeSchema) {}

export const OtpVerifySchema = z
  .object({
    challengeId: z.uuid(),
    code: z.string().regex(/^\d{6}$/),
    deviceId,
    app: signupApp,
    platform: z.enum(['android', 'ios', 'web']),
    appVersion: z.string().max(32).optional(),
  });
export class OtpVerifyDto extends createZodDto(OtpVerifySchema) {}

export const MeSchema = z
  .object({
    id: z.uuid(),
    phoneMasked: z.string(),
    name: z.string().nullable(),
    locale: z.string(),
    roles: z.array(role),
  });
export class MeDto extends createZodDto(MeSchema) {}

export const TokenPairSchema = z
  .object({
    accessToken: z.string(),
    refreshToken: z.string(),
    accessExpiresIn: z.number().int().describe('seconds'),
    refreshExpiresIn: z.number().int().describe('seconds'),
  });
export class TokenPairDto extends createZodDto(TokenPairSchema) {}

export const AuthSessionSchema = TokenPairSchema.extend({
  user: MeSchema,
  isNewUser: z.boolean(),
});
export class AuthSessionDto extends createZodDto(AuthSessionSchema) {}

export const OpsLoginSchema = z.object({
  email: z.email().max(200),
  password: z.string().min(8).max(200),
  deviceId,
});
export class OpsLoginDto extends createZodDto(OpsLoginSchema) {}

export const OpsChallengeSchema = OtpChallengeSchema.extend({
  phoneMasked: z.string().describe('Where the second-factor code was sent'),
});
export class OpsChallengeDto extends createZodDto(OpsChallengeSchema) {}

export const OpsVerifySchema = z.object({ challengeId: z.uuid(), code: z.string().regex(/^\d{6}$/), deviceId });
export class OpsVerifyDto extends createZodDto(OpsVerifySchema) {}

export const RefreshSchema = z
  .object({ refreshToken: z.string().min(10).max(512), deviceId });
export class RefreshDto extends createZodDto(RefreshSchema) {}
